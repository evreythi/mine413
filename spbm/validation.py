# ------------------------------------------------------------- 1. balances
def mass_metal_balance(rec, agg, df) -> pd.DataFrame:
    tin = rec.totals_in
    col = rec.cols.totals()
    blk = agg.reshape(-1, NP).sum(0)
    rows = []
    for name, key, unit in [("FMS tonnes", "T_F", "t"), ("FMS Cu", "CU_F", "t Cu"), ("FMS Au", "AU_F", "kg Au"), ("FMS Ag", "AG_F", "kg Ag")]:
        rows.append({"quantity": name, "unit": unit, "FMS_input": tin[key], "column_model": col[P[key]],
                     "block_model_grid": blk[P[key]], "block_table": df[{"T_F": "t_fms", "CU_F": "cu_t", "AU_F": "au_kg", "AG_F": "ag_kg"}[key]].sum() if key == "T_F" else np.nan})
    out = pd.DataFrame(rows)
    out["abs_diff_block_vs_input"] = out["block_model_grid"] - out["FMS_input"]
    out["rel_diff_ppm"] = out["abs_diff_block_vs_input"] / out["FMS_input"] * 1e6
    return out


def class_inventory(rec, agg) -> pd.DataFrame:
    blk = agg.reshape(-1, NP).sum(0)
    rows = []
    for cls, lab in [("F", "FMS-tracked (reconciled + provisional)"), ("U", "Unattributed (imputed grade)"), ("L", "Legacy (assumed grade)")]:
        t = blk[P[f"T_{cls}"]]
        rows.append({"class": lab, "tonnes": t, "cu_t": blk[P[f"CU_{cls}"]], "au_kg": blk[P[f"AU_{cls}"]],
                     "ag_kg": blk[P[f"AG_{cls}"]], "cu_pct": blk[P[f"CU_{cls}"]] / t * 100, "au_gpt": blk[P[f"AU_{cls}"]] / t * 1000})
    df = pd.DataFrame(rows)
    tot = df[["tonnes", "cu_t", "au_kg", "ag_kg"]].sum()
    df.loc[len(df)] = {"class": "TOTAL", "tonnes": tot.tonnes, "cu_t": tot.cu_t, "au_kg": tot.au_kg, "ag_kg": tot.ag_kg,
                       "cu_pct": tot.cu_t / tot.tonnes * 100, "au_gpt": tot.au_kg / tot.tonnes * 1000}
    df["share_of_tonnes"] = df["tonnes"] / tot.tonnes
    return df


def volume_reconciliation(rec) -> pd.DataFrame:
    p = rec.periods
    rows = {
        "survey change-solid volume (m3)": p["solid_volume"].sum(),
        "observed fill used by model (m3)": p["fill_volume"].sum(),
        "  of which unobserved fill on first-surveyed cells (m3)": p["unobserved_fill_new_cells"].sum(),
        "cut / re-handled volume (m3)": p["cut_volume"].sum(),
        "sub-threshold change not modelled (m3)": p["noise_volume"].sum(),
        "FMS volume (tonnes / density) (m3)": rec.loads["vol"].sum(),
        "FMS volume placed into observed fill (m3)": p["placed_volume"].sum() - 0,
        "unattributed fill volume (m3)": p["unattributed_volume"].sum(),
        "FMS volume never reconciled (provisional) (m3)": rec.destinations.loc[rec.destinations["kind"].str.startswith("provisional"), "volume_in"].sum(),
        "max Sinkhorn column residual (relative)": p["sinkhorn_col_err"].max(),
    }
    return pd.DataFrame({"item": list(rows), "value": list(rows.values())})


